// MARK: 4. Engine against an in-memory server
final class MemTransport: ClipTransport {
    var profile = ClipProfile(type: "Text", hash: "", text: "", hasData: false, dataName: nil)
    var files: [String: Data] = [:]
    var puts = 0
    var failNext: HubError?       // next request fails with this
    var holdGet: DispatchSemaphore?   // block getProfile until signalled (race tests)
    let q = DispatchQueue(label: "mem")
    func setRemote(_ text: String) { profile = ClipProfile(type: "Text", hash: ClipHash.text(text), text: text, hasData: false, dataName: nil, size: Int64(text.utf16.count)) }
    private func takeFail() -> HubError? { let f = failNext; failNext = nil; return f }
    func getProfile(_ c: @escaping (Result<ClipProfile, HubError>) -> Void) {
        let snap = profile; let f = takeFail(); let hold = holdGet
        (hold == nil ? q : DispatchQueue.global()).async { hold?.wait(); if let f = f { c(.failure(f)) } else { c(.success(snap)) } }
    }
    func putProfile(_ p: ClipProfile, _ c: @escaping (Result<Void, HubError>) -> Void) {
        if let f = takeFail() { q.async { c(.failure(f)) }; return }
        // round-trip through JSON like the real server
        profile = try! ClipProfile.parse(p.jsonData()); puts += 1; q.async { c(.success(())) }
    }
    func getFile(_ n: String, maxBytes: Int64, _ c: @escaping (Result<Data, HubError>) -> Void) {
        if let f = takeFail() { q.async { c(.failure(f)) }; return }
        let d = files[n]; q.async { c(d.map { .success($0) } ?? .failure(.http(404, ""))) }
    }
    func putFile(_ n: String, _ d: Data, _ c: @escaping (Result<Void, HubError>) -> Void) {
        if let f = takeFail() { q.async { c(.failure(f)) }; return }
        files[n] = d; q.async { c(.success(())) }
    }
}

